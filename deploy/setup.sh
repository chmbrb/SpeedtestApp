#!/usr/bin/env bash
# Creates deploy/.env with freshly generated secrets, then tells you what to do next.
#
#   ./setup.sh [--force] [HOST]
#
# HOST is how your phone and browsers reach this machine (an address or name, no http://). If you leave it out the script
# guesses this machine's first network address; check the result. Existing .env files are never overwritten without --force.
set -euo pipefail
cd "$(dirname "$0")"

FORCE=0
if [ "${1:-}" = "--force" ]; then FORCE=1; shift; fi
HOST="${1:-}"
DOCKER="${DOCKER:-docker}"
NTFY_IMAGE="${NTFY_IMAGE:-binwiederhier/ntfy:v2.29.0}"

if [ -e .env ] && [ "$FORCE" -ne 1 ]; then
  echo ".env already exists, so nothing was changed. Use --force to replace it (this makes NEW passwords: the database and"
  echo "ntfy would then reject the old ones, so only do that on a stack you are about to wipe with 'docker compose down -v')."
  exit 1
fi

rand() { # rand <hex digits>: letters and digits only, so the value is safe in a URL and in a .env file
  if command -v openssl >/dev/null 2>&1; then openssl rand -hex "$(($1 / 2))"; else head -c "$(($1 / 2))" /dev/urandom | od -An -tx1 | tr -d ' \n'; fi
}
hash() { # bcrypt hash of $1, produced by the same ntfy image the stack runs
  local h
  h="$(printf '%s\n%s\n' "$1" "$1" | "$DOCKER" run --rm -i "$NTFY_IMAGE" user hash 2>/dev/null | grep -o '\$2[aby]\$[0-9]*\$[./A-Za-z0-9]*' | tail -1)" || true
  [ -n "$h" ] || { echo "Could not create a password hash with '$DOCKER run $NTFY_IMAGE'. Is Docker running?" >&2; exit 1; }
  printf '%s' "$h"
}

if [ -z "$HOST" ]; then
  HOST="$( (hostname -I 2>/dev/null || true) | awk '{print $1}')"
  HOST="${HOST:-localhost}"
  GUESSED=1
else
  GUESSED=0
fi
TZ_NAME="$( (timedatectl show -p Timezone --value 2>/dev/null || cat /etc/timezone 2>/dev/null) | head -1)"
[[ "$TZ_NAME" =~ ^[A-Za-z0-9_+/-]+$ ]] || TZ_NAME=UTC

HTTP_PORT="${HTTP_PORT:-8080}"
HTTPS_PORT="${HTTPS_PORT:-8443}"
NTFY_PORT="${NTFY_PORT:-8081}"
DB_ADMIN_PASSWORD="$(rand 32)"
DB_APP_PASSWORD="$(rand 32)"
API_TOKEN="$(rand 40)"
NTFY_TOPIC="speedtest-$(rand 16)"
NTFY_BACKEND_PASSWORD="$(rand 32)"
NTFY_PHONE_PASSWORD="$(rand 16)"
echo "Creating password hashes with $NTFY_IMAGE ..."
NTFY_BACKEND_HASH="$(hash "$NTFY_BACKEND_PASSWORD")"
NTFY_PHONE_HASH="$(hash "$NTFY_PHONE_PASSWORD")"

umask 077
cat > .env <<ENV
# Generated by setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Contains secrets: keep it private and out of git.
# See .env.example for what each setting means.

DB_ADMIN_PASSWORD=$DB_ADMIN_PASSWORD
DB_APP_PASSWORD=$DB_APP_PASSWORD
API_TOKENS=server=$API_TOKEN

HTTP_PORT=$HTTP_PORT
# HTTPS with your own private certificate authority (no domain needed). Browsers only allow installing the app and
# notifications on https pages. HTTPS_HOSTS is every address or name people type, separated by commas.
HTTPS_PORT=$HTTPS_PORT
HTTPS_HOSTS=$HOST
APP_URL=https://$HOST:$HTTPS_PORT
NTFY_PORT=$NTFY_PORT
NTFY_BASE_URL=http://$HOST:$NTFY_PORT
TIMEZONE=$TZ_NAME

NTFY_TOPIC=$NTFY_TOPIC
NTFY_BACKEND_PASSWORD=$NTFY_BACKEND_PASSWORD
NTFY_PHONE_PASSWORD=$NTFY_PHONE_PASSWORD
# Single quotes: bcrypt hashes contain "\$", which must stay literal.
NTFY_BACKEND_HASH='$NTFY_BACKEND_HASH'
NTFY_PHONE_HASH='$NTFY_PHONE_HASH'

DEVICE_NAME=server
SERVER_CONNECTION_TYPE=wired
# Leave empty until you have read Ookla's terms (https://www.speedtest.net/about/eula) and agree to them. Then set it to: yes
OOKLA_ACCEPT_LICENSE=
ENV

cat <<DONE

Wrote $(pwd)/.env (only you can read it).

Next:
  1. Start everything:     docker compose up -d --build
  2. Open the dashboard:   https://$HOST:$HTTPS_PORT   (or plain http://$HOST:$HTTP_PORT, without install and notifications)
     First time on each device: trust the HTTPS certificate once. Open https://$HOST:$HTTPS_PORT/ca.crt, install it,
     and follow "HTTPS on your network" in docs/DEPLOY.md.
  3. On your phone, install the ntfy app, then add a subscription:
       server:   http://$HOST:$NTFY_PORT
       login:    user "phone", password "$NTFY_PHONE_PASSWORD"
       topic:    $NTFY_TOPIC
  4. Check notifications work:   docker compose run --rm backend notify-test
  5. Feed it results: run speedtest-collector on this machine (build it with collector-go/build.sh; see docs/COLLECTOR.md):
       SPEEDTEST_API_TOKEN=$API_TOKEN speedtest-collector daemon --api-url http://$HOST:$HTTP_PORT --connection wired

DONE
if [ "$GUESSED" -eq 1 ]; then
  echo "I guessed this machine's address as $HOST. If your phone cannot reach that, fix APP_URL and NTFY_BASE_URL in .env."
fi
echo "To turn on the \"Test the server\" button, read docs/DEPLOY.md first: it needs you to accept Ookla's terms yourself."
